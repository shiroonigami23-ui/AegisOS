#!/usr/bin/env python3
import argparse
import json
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from statistics import mean


def repo_root() -> Path:
  return Path(__file__).resolve().parents[1]


def utc_now_iso() -> str:
  return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace('+00:00', 'Z')


def run_hotpath_benchmark(iterations: int) -> dict:
  root = repo_root()
  cmd = [
      sys.executable,
      str(root / "scripts" / "kernel_hotpath_benchmark.py"),
      "--iterations",
      str(iterations),
  ]
  result = subprocess.run(cmd, cwd=root, check=True, capture_output=True, text=True)
  return json.loads(result.stdout)


def load_budget() -> dict:
  budget_path = repo_root() / "docs" / "PERF_BUDGET.json"
  return json.loads(budget_path.read_text(encoding="utf-8"))


def level_for_metric(metric: dict, budget: dict) -> str:
  min_ops = float(budget.get("min_ops_per_sec", 0.0))
  max_ns = float(budget.get("max_ns_per_op", float("inf")))
  ops = float(metric.get("ops_per_sec", 0.0))
  ns = float(metric.get("ns_per_op", 0.0))
  if ops >= min_ops and ns <= max_ns:
    if ops >= min_ops * 2.0 and ns <= max_ns * 0.5:
      return "strong"
    return "target"
  if ops >= min_ops * 0.8 and ns <= max_ns * 1.25:
    return "near-target"
  return "below-target"


def write_json(path: Path, payload: dict) -> None:
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(json.dumps(payload, sort_keys=True, separators=(",", ":")) + "\n", encoding="utf-8")


def append_history(path: Path, payload: dict) -> None:
  path.parent.mkdir(parents=True, exist_ok=True)
  with path.open("a", encoding="utf-8") as f:
    f.write(json.dumps(payload, sort_keys=True, separators=(",", ":")) + "\n")


def load_history(path: Path) -> list[dict]:
  if not path.exists():
    return []
  out: list[dict] = []
  for line in path.read_text(encoding="utf-8").splitlines():
    line = line.strip()
    if not line:
      continue
    try:
      out.append(json.loads(line))
    except json.JSONDecodeError:
      continue
  return out


def render_status_md(status_path: Path, latest: dict, history: list[dict], budgets: dict) -> None:
  metrics = [
      "scheduler_next",
      "namespace_translate_local_to_global",
      "namespace_can_inspect",
      "ipc_reserve_send_plus_drain",
      "memory_charge_plus_release",
  ]
  recent = history[-20:]

  lines: list[str] = []
  lines.append("# Benchmark Status")
  lines.append("")
  lines.append("Auto-generated by `scripts/benchmark_monitor.py`.")
  lines.append("")
  lines.append(f"- Latest timestamp (UTC): `{latest['observed_at_utc']}`")
  lines.append(f"- Iterations: `{latest['benchmark']['iterations']}`")
  lines.append("")
  lines.append("## Latest Metrics")
  lines.append("")
  lines.append("| Metric | ns/op | ops/sec | Budget Level |")
  lines.append("|---|---:|---:|---|")

  for name in metrics:
    metric = latest["benchmark"].get(name, {})
    budget = budgets.get(name, {})
    level = level_for_metric(metric, budget)
    lines.append(
        f"| `{name}` | `{metric.get('ns_per_op', 0):.3f}` | `{metric.get('ops_per_sec', 0):.3f}` | `{level}` |"
    )

  lines.append("")
  lines.append("## Trend (Last 20 Runs)")
  lines.append("")
  lines.append("| Metric | avg ns/op | avg ops/sec |")
  lines.append("|---|---:|---:|")
  for name in metrics:
    ns_vals = [float(item.get("benchmark", {}).get(name, {}).get("ns_per_op", 0.0)) for item in recent]
    ops_vals = [float(item.get("benchmark", {}).get(name, {}).get("ops_per_sec", 0.0)) for item in recent]
    if ns_vals and ops_vals:
      lines.append(f"| `{name}` | `{mean(ns_vals):.3f}` | `{mean(ops_vals):.3f}` |")
    else:
      lines.append(f"| `{name}` | `0.000` | `0.000` |")

  lines.append("")
  lines.append("## Notes")
  lines.append("")
  lines.append("- This benchmark compares AegisOS kernel hotpath internals over time, not full end-user app performance yet.")
  lines.append("- For real-world external comparisons, combine this with workload-level suites (compile, I/O, browser, and gaming traces).")

  status_path.parent.mkdir(parents=True, exist_ok=True)
  status_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
  parser = argparse.ArgumentParser(description="Run and monitor AegisOS benchmark trends.")
  parser.add_argument("--iterations", type=int, default=120000)
  parser.add_argument("--history", default="benchmarks/history/kernel_hotpath_history.jsonl")
  parser.add_argument("--latest-json", default="benchmarks/latest/kernel_hotpath_latest.json")
  parser.add_argument("--status-md", default="docs/BENCHMARK_STATUS.md")
  args = parser.parse_args()

  if args.iterations <= 0:
    raise ValueError("iterations must be > 0")

  budget_doc = load_budget()
  thresholds = budget_doc.get("thresholds", {})

  bench = run_hotpath_benchmark(args.iterations)
  snapshot = {
      "observed_at_utc": utc_now_iso(),
      "benchmark": bench,
      "budget_thresholds": thresholds,
      "runner": {
          "platform": os.name,
          "python": sys.version.split()[0],
      },
  }

  root = repo_root()
  history_path = root / args.history
  latest_path = root / args.latest_json
  status_path = root / args.status_md

  append_history(history_path, snapshot)
  write_json(latest_path, snapshot)
  history = load_history(history_path)
  render_status_md(status_path, snapshot, history, thresholds)

  print(json.dumps(snapshot, sort_keys=True, separators=(",", ":")))
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
