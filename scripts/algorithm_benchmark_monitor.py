#!/usr/bin/env python3
import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


def run_algo_bench(root: Path, iterations: int) -> dict:
  cmd = [
      sys.executable,
      str(root / "scripts" / "algorithm_selection_benchmark.py"),
      "--iterations",
      str(iterations),
  ]
  result = subprocess.run(cmd, cwd=root, capture_output=True, text=True, check=True)
  return json.loads(result.stdout)


def write_json(path: Path, payload: dict) -> None:
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(json.dumps(payload, sort_keys=True, separators=(",", ":")) + "\n", encoding="utf-8")


def append_history(path: Path, payload: dict) -> None:
  path.parent.mkdir(parents=True, exist_ok=True)
  with path.open("a", encoding="utf-8") as f:
    f.write(json.dumps(payload, sort_keys=True, separators=(",", ":")) + "\n")


def _fmt_metric(metric: dict) -> str:
  return f"{metric.get('ns_per_op', 0.0):.3f} ns/op | {metric.get('ops_per_sec', 0.0):.3f} ops/s"


def render_status(latest: dict, history_tail: list[dict]) -> str:
  bench = latest["benchmark"]
  lines = ["# Algorithm Lab Status", "", "Auto-generated by `scripts/algorithm_benchmark_monitor.py`.", ""]
  lines.append(f"- Updated at (UTC): `{latest['timestamp_utc']}`")
  lines.append(f"- Iterations: `{bench['iterations']}`")
  lines.append("")
  lines.append("## Winners")
  lines.append("")
  lines.append(f"- PID lookup: `{bench['winners']['pid_lookup']}`")
  lines.append(f"- Ready-pick: `{bench['winners']['ready_pick']}`")
  lines.append("")
  lines.append("## Metrics")
  lines.append("")
  lines.append(f"- PID linear scan: `{_fmt_metric(bench['pid_lookup']['linear_scan'])}`")
  lines.append(f"- PID hash chain: `{_fmt_metric(bench['pid_lookup']['bucket_hash_chain'])}`")
  lines.append(f"- Ready priority scan: `{_fmt_metric(bench['ready_pick']['priority_scan'])}`")
  lines.append(f"- Ready bit_length FF1: `{_fmt_metric(bench['ready_pick']['bit_length_ff1'])}`")
  lines.append("")
  if history_tail:
    lines.append("## Recent Winner History")
    lines.append("")
    for item in history_tail[-5:]:
      b = item.get("benchmark", {})
      w = b.get("winners", {})
      lines.append(
          f"- `{item.get('timestamp_utc', '?')}`: pid=`{w.get('pid_lookup', '?')}`, ready=`{w.get('ready_pick', '?')}`"
      )
    lines.append("")
  lines.append("## Wiki-Inspired Algorithm Set")
  lines.append("")
  lines.append("- Hash table with chaining/open addressing mindset for O(1)-ish key lookup.")
  lines.append("- Bitset/bitmap first-set-bit style dispatch class selection.")
  lines.append("- Round-robin baseline retained for fairness and predictability.")
  lines.append("")
  return "\n".join(lines) + "\n"


def read_history(path: Path) -> list[dict]:
  if not path.exists():
    return []
  items = []
  for line in path.read_text(encoding="utf-8").splitlines():
    line = line.strip()
    if not line:
      continue
    try:
      items.append(json.loads(line))
    except json.JSONDecodeError:
      continue
  return items


def main() -> int:
  parser = argparse.ArgumentParser(description="Run algorithm simulation benchmark and maintain status/history")
  parser.add_argument("--iterations", type=int, default=250000)
  parser.add_argument("--history", default="benchmarks/history/algorithm_selection_history.jsonl")
  parser.add_argument("--latest-json", default="benchmarks/latest/algorithm_selection_latest.json")
  parser.add_argument("--status-md", default="docs/ALGORITHM_LAB_STATUS.md")
  args = parser.parse_args()

  root = Path(__file__).resolve().parents[1]
  bench = run_algo_bench(root, args.iterations)
  snapshot = {
      "timestamp_utc": datetime.now(timezone.utc).isoformat(),
      "benchmark": bench,
  }

  history_path = root / args.history
  latest_path = root / args.latest_json
  status_path = root / args.status_md

  write_json(latest_path, snapshot)
  append_history(history_path, snapshot)
  history = read_history(history_path)
  status_path.write_text(render_status(snapshot, history), encoding="utf-8")
  print(json.dumps(snapshot, sort_keys=True, separators=(",", ":")))
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
